def context_block(nickname: str, today: str, memories: list[str], has_profile: bool) -> str:
    lines = [
        "## 현재 대화 정보 (시스템 제공)",
        f"- 사용자 호칭: {nickname}님",
        f"- 오늘 날짜: {today}",
        "- 재무 프로필: " + ("있음 (get_my_finances로 조회)" if has_profile else "아직 없음 (진단을 먼저 권하세요)"),
    ]
    if memories:
        lines.append("- 지난 대화에서 기억한 내용:")
        lines += [f"  - {m}" for m in memories]
    return "\n".join(lines)


